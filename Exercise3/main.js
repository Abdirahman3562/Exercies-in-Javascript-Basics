
let isSunny = true;
let isWeekend = true;

// and &&
// Labada dhinacba waa inay true noqdaan si uu true u soo baxo
console.log(isSunny && isWeekend); 
console.log("xeebta waa aadi kartaa")
// Output: false

// or ||
// Ugu yaraan hal dhinac haduu true yahay wuxuu soo celinayaa true
console.log(isSunny || isWeekend); 
console.log("xeebta waa aadi kartaa");
// Output: true

// not !
// Wuxuu rogaa qiimaha (true -> false, false -> true)
console.log(!isSunny); // Output: false
console.log("xeebta ma aadi kartid");
console.log(!isWeekend); // Output: false
console.log("xeebta ma aadi kartid");
